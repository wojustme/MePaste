import AppKit
import Foundation

@MainActor
final class ClipboardMonitor {
    var onNewRecord: ((ClipboardRecord) -> Void)?

    var isPaused = false {
        didSet {
            guard isPaused != oldValue else { return }
            resetCaptureBoundary()
        }
    }
    var excludedApplicationBundleIdentifiers: Set<String> = [] {
        didSet {
            guard excludedApplicationBundleIdentifiers != oldValue else { return }
            resetCaptureBoundary()
        }
    }

    var changeCount: Int { pasteboard.changeCount }

    private static let privateTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType"
    ]

    private let pasteboard: NSPasteboard
    private let frontmostApplicationIdentifier: () -> String?
    private let recordBuilder = ClipboardRecordBuilder()
    private var timer: Timer?
    private var lastChangeCount: Int
    private var pendingRecords: [UUID: Task<Void, Never>] = [:]
    private var session = 0

    init(
        pasteboard: NSPasteboard = .general,
        frontmostApplicationIdentifier: @escaping () -> String? = {
            NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        }
    ) {
        self.pasteboard = pasteboard
        self.frontmostApplicationIdentifier = frontmostApplicationIdentifier
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        session += 1
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            // This timer is installed only on the main run loop.
            MainActor.assumeIsolated {
                self?.checkForChanges()
            }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        resetCaptureBoundary()
    }

    private func resetCaptureBoundary() {
        session += 1
        for task in pendingRecords.values {
            task.cancel()
        }
        pendingRecords.removeAll()
        // Copies made while paused/excluded must not be picked up on resume,
        // including when the timer hasn't had a chance to observe them yet.
        lastChangeCount = pasteboard.changeCount
    }

    @discardableResult
    func write(_ record: ClipboardRecord, asPlainText: Bool = false) -> Bool {
        let items: [NSPasteboardItem]
        if asPlainText {
            guard let text = record.plainTextForPasting else { return false }
            let item = NSPasteboardItem()
            guard item.setString(text, forType: .string) else { return false }
            items = [item]
        } else {
            let groupedPayloads = Dictionary(grouping: record.payloads, by: \.itemIndex)
            items = groupedPayloads.keys.sorted().map { itemIndex in
                let item = NSPasteboardItem()
                for payload in groupedPayloads[itemIndex] ?? [] {
                    item.setData(
                        payload.data,
                        forType: NSPasteboard.PasteboardType(payload.type)
                    )
                }
                return item
            }
        }

        // Validate first so an unsupported plain-text action leaves the current
        // clipboard untouched rather than clearing it or copying rich data.
        guard !items.isEmpty else { return false }
        pasteboard.clearContents()
        let success = pasteboard.writeObjects(items)
        lastChangeCount = pasteboard.changeCount
        return success
    }

    func checkForChanges() {
        let changeCount = pasteboard.changeCount
        guard timer != nil, changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard !isPaused else { return }
        if let identifier = frontmostApplicationIdentifier(),
           excludedApplicationBundleIdentifiers.contains(identifier) {
            return
        }
        let createdAt = Date()

        guard let payloads = readCurrentPayloads() else { return }
        let identifier = UUID()
        let session = session
        pendingRecords[identifier] = Task { [weak self, recordBuilder] in
            let record = await recordBuilder.makeRecord(payloads: payloads, createdAt: createdAt)
            guard let self else { return }
            self.pendingRecords[identifier] = nil
            guard !Task.isCancelled, self.session == session, let record else { return }
            self.onNewRecord?(record)
        }
    }

    private func readCurrentPayloads() -> [ClipboardPayload]? {
        guard let items = pasteboard.pasteboardItems, !items.isEmpty else {
            return nil
        }
        guard !items.contains(where: { item in
            item.types.contains { Self.privateTypes.contains($0.rawValue) }
        }) else {
            return nil
        }

        var payloads: [ClipboardPayload] = []
        for (itemIndex, item) in items.enumerated() {
            for type in item.types {
                guard let data = item.data(forType: type)
                else { continue }
                payloads.append(
                    ClipboardPayload(itemIndex: itemIndex, type: type.rawValue, data: data)
                )
            }
        }

        return payloads.isEmpty ? nil : payloads
    }
}

private actor ClipboardRecordBuilder {
    func makeRecord(payloads: [ClipboardPayload], createdAt: Date) -> ClipboardRecord? {
        guard !Task.isCancelled else { return nil }
        return ClipboardRecord(createdAt: createdAt, payloads: payloads)
    }
}
